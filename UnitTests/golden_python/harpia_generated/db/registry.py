"""Public/private DB registry: every table this project owns, and the
cross-project access check it exists for.

Generated by harpia (python target), a port of the C++
``generated/cpp/db/harpia_db_registry.h``. Do not edit. A ``PUBLIC`` table is
reachable from any project; a ``PRIVATE`` one only from code built for the
same project name. Stdlib only, so another project can import this module
(for example by path) to ask "am I allowed at their table?". Nothing here is
enforced inside the DAOs (C++ doesn't either).
"""
import enum
from typing import NamedTuple


class Visibility(enum.Enum):
    """Who may reach a table."""

    PUBLIC = "PUBLIC"
    PRIVATE = "PRIVATE"


class AccessDecision(enum.Enum):
    """The answer of :func:`db_access_check`."""

    ALLOWED = "ALLOWED"
    DENIED_PRIVATE_CROSS_PROJECT = "DENIED_PRIVATE_CROSS_PROJECT"
    DENIED_UNKNOWN_TABLE = "DENIED_UNKNOWN_TABLE"


class RegistryEntry(NamedTuple):
    """One table, its visibility and the project that owns it."""

    table: str
    visibility: Visibility
    owner_project: str


#: this build's project name (``project.harpia.yaml`` -> ``project:``)
PROJECT_NAME = 'default'

# One row per table-bearing message, deduped by table name, sorted.
# note: table 'user_table' is also declared PRIVATE by message 'top_users' -- kept the first declaration below
REGISTRY: tuple[RegistryEntry, ...] = (
    RegistryEntry('alarm_event_table', Visibility.PRIVATE, 'default'),
    RegistryEntry('beacon_log_table', Visibility.PRIVATE, 'default'),
    RegistryEntry('crew_table', Visibility.PRIVATE, 'default'),
    RegistryEntry('journey_table', Visibility.PRIVATE, 'default'),
    RegistryEntry('outpost_table', Visibility.PRIVATE, 'default'),
    RegistryEntry('patient_vitals_table', Visibility.PRIVATE, 'default'),
    RegistryEntry('reception_desk_table', Visibility.PRIVATE, 'default'),
    RegistryEntry('shipment_table', Visibility.PRIVATE, 'default'),
    RegistryEntry('table_data', Visibility.PRIVATE, 'default'),
    RegistryEntry('table_vip_users', Visibility.PRIVATE, 'default'),
    RegistryEntry('telemetry_table', Visibility.PRIVATE, 'default'),
    RegistryEntry('user_table', Visibility.PUBLIC, 'default'),
    RegistryEntry('vault_table', Visibility.PRIVATE, 'default'),
)


def find_entry(table: str) -> RegistryEntry | None:
    """The registry row for ``table``, or ``None``."""
    for entry in REGISTRY:
        if entry.table == table:
            return entry
    return None


def db_access_check(requesting_project: str, table: str | None = None) -> AccessDecision:
    """Is ``requesting_project`` allowed to touch ``table``?

    Called with one argument, the argument is the table and the requesting
    project is :data:`PROJECT_NAME` (the C++ one-argument overload).
    """
    if table is None:
        requesting_project, table = PROJECT_NAME, requesting_project
    entry = find_entry(table)
    if entry is None:
        return AccessDecision.DENIED_UNKNOWN_TABLE
    if entry.visibility is Visibility.PUBLIC:
        return AccessDecision.ALLOWED
    if entry.owner_project == requesting_project:
        return AccessDecision.ALLOWED
    return AccessDecision.DENIED_PRIVATE_CROSS_PROJECT
